#!/usr/bin/env python3
"""Builds app/src/main/assets/dict/en_words.tsv and en_bigrams.tsv.

Source: SymSpell frequency dictionaries (MIT, https://github.com/wolfgarbe/SymSpell),
derived from the Google Books Ngram data (CC BY 3.0) intersected with SCOWL.
  frequency_dictionary_en_82_765.txt        word count
  frequency_bigramdictionary_en_243_342.txt word1 word2 count

Usage:
  pip download --no-deps symspellpy -d /tmp/ss && unzip -j /tmp/ss/*.whl \
      'symspellpy/frequency_*.txt' -d /tmp/ss
  python3 tools/build_english_dict.py /tmp/ss/frequency_dictionary_en_82_765.txt \
      /tmp/ss/frequency_bigramdictionary_en_243_342.txt

Hand-curated words and bigrams (contractions like don't, chat words) in
tools/en_curated*.tsv are merged in and never ranked lower than their curated value.
"""
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT = ROOT / "app/src/main/assets/dict"
TOOLS = ROOT / "tools"

MAX_WORDS = 40000           # memory budget on the phone
SCALE_MAX = 200000          # frequency of the most common word
MAX_FOLLOWERS = 10          # predictions kept per previous word
BIGRAM_SCALE_MAX = 5000     # count of the most common bigram

WORD = re.compile(r"^[a-z]+$")
SINGLE_LETTER_WORDS = {"a", "i"}


def keep(word: str) -> bool:
    return bool(WORD.match(word)) and (len(word) > 1 or word in SINGLE_LETTER_WORDS)


def curated(path: Path):
    for line in open(path, encoding="utf-8"):
        if line.strip() and not line.startswith("#"):
            yield line.rstrip("\n").split("\t")


def main(words_path: str, bigrams_path: str) -> None:
    counts = {}
    for line in open(words_path, encoding="utf-8"):
        parts = line.split()
        if len(parts) == 2 and keep(parts[0]):
            counts[parts[0]] = int(parts[1])
    ranked = sorted(counts.items(), key=lambda kv: -kv[1])[:MAX_WORDS]
    top = ranked[0][1]
    # Square-root compression keeps rare words distinguishable instead of all becoming 1.
    freqs = {w: max(1, round(SCALE_MAX * math.sqrt(c / top))) for w, c in ranked}
    for w, f in curated(TOOLS / "en_curated.tsv"):
        freqs[w] = max(freqs.get(w, 0), int(f))

    followers = defaultdict(list)
    for line in open(bigrams_path, encoding="utf-8"):
        parts = line.split()
        if len(parts) == 3 and parts[0] in freqs and parts[1] in freqs:
            followers[parts[0]].append((parts[1], int(parts[2])))
    btop = max(c for lst in followers.values() for _, c in lst)
    bigrams = {}
    for prev, lst in followers.items():
        for w, c in sorted(lst, key=lambda x: -x[1])[:MAX_FOLLOWERS]:
            bigrams[(prev, w)] = max(1, round(BIGRAM_SCALE_MAX * math.sqrt(c / btop)))
    for a, b, f in curated(TOOLS / "en_curated_bigrams.tsv"):
        bigrams[(a, b)] = max(bigrams.get((a, b), 0), int(f))

    header = ("# Generated by tools/build_english_dict.py from SymSpell (MIT) frequency data,\n"
              "# derived from Google Books Ngrams (CC BY 3.0) and SCOWL.\n")
    with open(DICT / "en_words.tsv", "w", encoding="utf-8") as out:
        out.write("# word<TAB>frequency (English)\n" + header)
        for w, f in sorted(freqs.items(), key=lambda kv: (-kv[1], kv[0])):
            out.write(f"{w}\t{f}\n")
    with open(DICT / "en_bigrams.tsv", "w", encoding="utf-8") as out:
        out.write("# previous<TAB>word<TAB>frequency (English)\n" + header)
        for (a, b), f in sorted(bigrams.items(), key=lambda kv: (kv[0][0], -kv[1])):
            out.write(f"{a}\t{b}\t{f}\n")
    print(f"wrote {len(freqs)} words, {len(bigrams)} bigrams")


if __name__ == "__main__":
    main(*sys.argv[1:3])
