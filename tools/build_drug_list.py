#!/usr/bin/env python3
"""Builds app/src/main/assets/dict/en_medical.tsv (generic drug names).

Source: the DrugBank Open Data vocabulary (CC0-1.0) as packaged in the
`drug-named-entity-recognition` PyPI package (MIT). Only entries that carry a
DrugBank ID are used, so names from other bundled sources are excluded.

The package stores its data as a pickle; it is read with a restricted
unpickler that only accepts plain built-in data types, never code.

Usage:
  pip download --no-deps drug-named-entity-recognition -d /tmp/dn
  unzip -j /tmp/dn/*.whl '*/drug_ner_dictionary.pkl.bz2' -d /tmp/dn
  python3 tools/build_drug_list.py /tmp/dn/drug_ner_dictionary.pkl.bz2
"""
import bz2
import pickle
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/dict/en_medical.tsv"
EXTRA = ROOT / "tools/en_medical_extra.txt"

COMMON_FREQ = 1500   # drugs with a MedlinePlus monograph (in routine clinical use)
OTHER_FREQ = 300     # everything else in DrugBank
NAME = re.compile(r"[a-z][a-z \-]{2,40}")
SKIP = re.compile(r"pollen|extract|allergenic|dander|venom|\bhair\b|feather|mold|mite|smut|epithelia")

SAFE = {("builtins", n) for n in ("dict", "list", "set", "frozenset", "tuple", "str", "int", "float", "bool")}


class SafeUnpickler(pickle.Unpickler):
    def find_class(self, module, name):
        if (module, name) in SAFE:
            return super().find_class(module, name)
        raise pickle.UnpicklingError(f"refusing to load {module}.{name}")


def main(pkl: str) -> None:
    data = SafeUnpickler(bz2.open(pkl)).load()
    terms = {}
    for key, info in data["drug_canonical_to_data"].items():
        if not info.get("drugbank_id"):
            continue
        if not NAME.fullmatch(key) or len(key.split()) > 3 or SKIP.search(key):
            continue
        terms[key] = COMMON_FREQ if info.get("medline_plus_id") else OTHER_FREQ
    for line in open(EXTRA, encoding="utf-8"):
        line = line.strip().lower()
        if line and not line.startswith("#"):
            terms[line] = COMMON_FREQ
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("# Generic drug names<TAB>frequency. Generated by tools/build_drug_list.py\n")
        out.write("# Source: DrugBank Open Data vocabulary (CC0-1.0) + tools/en_medical_extra.txt\n")
        for term, f in sorted(terms.items()):
            out.write(f"{term}\t{f}\n")
    print(f"wrote {len(terms)} terms ({sum(f == COMMON_FREQ for f in terms.values())} common)")


if __name__ == "__main__":
    main(sys.argv[1])
