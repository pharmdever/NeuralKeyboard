#!/usr/bin/env python3
"""Generates all app icons as Android vector drawables from code.

Every icon is defined once here as SVG path data. The script writes
  app/src/main/res/drawable/ic_*.xml            keyboard / UI icons (24dp, tinted at runtime)
  app/src/main/res/mipmap/ic_launcher.xml        launcher icon for Android 7.x
  app/src/main/res/mipmap-anydpi-v26/...         adaptive launcher icon (+ themed monochrome)
  tools/icons/preview.html                       visual preview of everything

Usage: python3 tools/icons/build_icons.py
"""
