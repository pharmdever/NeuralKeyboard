STROKE_WIDTH = 1.9


def ui_vector(paths):
    parts = []
    for d, style in paths:
        fill = 'android:fillColor="#FFFFFFFF"' if "fill" in style else 'android:fillColor="#00000000"'
        stroke = ('android:strokeColor="#FFFFFFFF" android:strokeWidth="%s" '
                  'android:strokeLineCap="round" android:strokeLineJoin="round"' % STROKE_WIDTH) if "stroke" in style else ""
        parts.append(f'    <path {fill} {stroke} android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/icons/build_icons.py. White; tinted at runtime. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n'
            + "\n".join(parts) + "\n</vector>\n")


# --------------------------------------------------------------------------- launcher
# 108x108 adaptive-icon canvas; keep the artwork inside the 66dp safe circle (21..87).
GRADIENT = ("#3D5AFE", "#00B8D4")   # indigo -> cyan

def rrect(x1, y1, x2, y2, r):
    return (f"M{x1 + r} {y1} H{x2 - r} A{r} {r} 0 0 1 {x2} {y1 + r} V{y2 - r} "
            f"A{r} {r} 0 0 1 {x2 - r} {y2} H{x1 + r} A{r} {r} 0 0 1 {x1} {y2 - r} "
            f"V{y1 + r} A{r} {r} 0 0 1 {x1 + r} {y1} Z")

def keyboard_body():
    """White keyboard with keys cut out (even-odd), so the gradient shows through."""
    d = [rrect(27, 41, 81, 77, 7)]
    kw, kh, gap = 7.2, 6.2, 2.6
    for row, (y, offset, count) in enumerate([(46.5, 0, 5), (55.3, 4.9, 4)]):
        x0 = 32.3 + offset
        for i in range(count):
            x = x0 + i * (kw + gap)
            d.append(rrect(round(x, 2), y, round(x + kw, 2), y + kh, 1.6))
    d.append(rrect(41, 65.3, 67, 71.3, 1.6))  # space bar
    return " ".join(d)

def sparkle(cx, cy, r):
    """Four-pointed star: the 'smart' part of the smart keyboard."""
    k = r * 0.22
    return (f"M{cx} {cy - r} C{cx + k} {cy - k} {cx + k} {cy - k} {cx + r} {cy} "
            f"C{cx + k} {cy + k} {cx + k} {cy + k} {cx} {cy + r} "
            f"C{cx - k} {cy + k} {cx - k} {cy + k} {cx - r} {cy} "
            f"C{cx - k} {cy - k} {cx - k} {cy - k} {cx} {cy - r} Z")

FOREGROUND = [(keyboard_body(), "evenOdd"), (sparkle(73, 33, 8.5), "nonZero"), (sparkle(62.5, 27.5, 3.6), "nonZero")]

def gradient_attr(x1, y1, x2, y2):
    return ('        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
            f'android:endX="{x2}" android:endY="{y2}" android:startColor="{GRADIENT[0]}" '
            f'android:endColor="{GRADIENT[1]}" />\n'
            '        </aapt:attr>\n')

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icons/build_icons.py -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp" android:height="108dp"\n'
          '    android:viewportWidth="108" android:viewportHeight="108">\n')

def fg_paths(color="#FFFFFFFF"):
    return "".join(f'    <path android:fillColor="{color}" android:fillType="{ft}" android:pathData="{d}" />\n'
                   for d, ft in FOREGROUND)

def launcher_background():
    return HEADER + '    <path android:pathData="M0 0 H108 V108 H0 Z">\n' + gradient_attr(0, 0, 108, 108) + '    </path>\n</vector>\n'

def launcher_foreground():
    return HEADER + fg_paths() + "</vector>\n"

def launcher_legacy():
    """Android 7.x has no adaptive icons: a rounded square with the same artwork."""
    return (HEADER + f'    <path android:pathData="{rrect(6, 6, 102, 102, 22)}">\n'
            + gradient_attr(6, 6, 102, 102) + '    </path>\n' + fg_paths() + "</vector>\n")

ADAPTIVE = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icons/build_icons.py -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
            '</adaptive-icon>\n')

# --------------------------------------------------------------------------- preview
def svg_ui(paths, color):
    out = []
    for d, style in paths:
        fill = color if "fill" in style else "none"
        stroke = f'stroke="{color}" stroke-width="{STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round"' if "stroke" in style else ""
        out.append(f'<path d="{d}" fill="{fill}" {stroke}/>')
    return f'<svg viewBox="0 0 24 24" width="48" height="48">{"".join(out)}</svg>'

def svg_launcher(shape):
    grad = (f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{GRADIENT[0]}"/>'
            f'<stop offset="1" stop-color="{GRADIENT[1]}"/></linearGradient></defs>')
    fg = "".join(f'<path d="{d}" fill="#fff" fill-rule="{"evenodd" if ft == "evenOdd" else "nonzero"}"/>' for d, ft in FOREGROUND)
    clip = {"circle": '<clipPath id="c"><circle cx="54" cy="54" r="54"/></clipPath>',
            "squircle": f'<clipPath id="c"><path d="{rrect(0, 0, 108, 108, 34)}"/></clipPath>'}[shape]
    return (f'<svg viewBox="0 0 108 108" width="132" height="132">{grad}<defs>{clip}</defs>'
            f'<g clip-path="url(#c)"><rect width="108" height="108" fill="url(#g)"/>{fg}</g></svg>')

def preview():
    cells = []
    for name, paths in UI_ICONS.items():
        cells.append(f'<figure><div class="tile light">{svg_ui(paths, "#1f2933")}</div>'
                     f'<div class="tile dark">{svg_ui(paths, "#e8eef3")}</div><figcaption>{name[3:]}</figcaption></figure>')
    return f"""<!doctype html><html><head><meta charset="utf-8"><style>
body{{font-family:system-ui,sans-serif;background:#f4f6f8;margin:24px;color:#1f2933}}
h2{{font-size:15px;margin:22px 0 10px}} .row{{display:flex;flex-wrap:wrap;gap:14px}}
figure{{margin:0;text-align:center;font-size:11px;color:#52606d}}
.tile{{width:64px;height:64px;border-radius:12px;display:flex;align-items:center;justify-content:center;margin-bottom:4px}}
.light{{background:#fff;box-shadow:0 1px 2px #0002}} .dark{{background:#2a2e33}}
.launch{{display:flex;gap:28px;align-items:end}}
</style></head><body>
<h2>Launcher icon (circle / squircle masks)</h2><div class="launch">{svg_launcher("circle")}{svg_launcher("squircle")}</div>
<h2>Keyboard &amp; clipboard icons (light / dark theme)</h2><div class="row">{''.join(cells)}</div>
</body></html>"""

# --------------------------------------------------------------------------- write
def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")

def main():
    for name, paths in UI_ICONS.items():
        write(RES / "drawable" / f"{name}.xml", ui_vector(paths))
    write(RES / "drawable" / "ic_launcher_background.xml", launcher_background())
    write(RES / "drawable" / "ic_launcher_foreground.xml", launcher_foreground())
    write(RES / "mipmap" / "ic_launcher.xml", launcher_legacy())
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", ADAPTIVE)
    write(ROOT / "tools/icons/preview.html", preview())
    print(f"wrote {len(UI_ICONS)} UI icons + launcher icon")

if __name__ == "__main__":
    main()
