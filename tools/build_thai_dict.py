#!/usr/bin/env python3
"""Builds th_words.tsv and th_bigrams.tsv from PyThaiNLP corpus files.

Sources (all CC0-1.0, https://github.com/PyThaiNLP/pythainlp-corpus):
  tnc_freq.txt       word<TAB>count from the Thai National Corpus
  words_th.txt       Thai word list, used to drop tokenizer fragments among rare words
  201705_2gram.txt   word1<TAB>word2<TAB>count, TNC bigrams (optional third argument)

Usage:
  pip download --no-deps pythainlp -d /tmp/pt && unzip -j /tmp/pt/*.whl \
      'pythainlp/corpus/tnc_freq.txt' 'pythainlp/corpus/words_th.txt' -d /tmp/pt
  curl -L -o /tmp/pt/2gram.txt \
      https://github.com/PyThaiNLP/pythainlp-corpus/releases/download/tnc-v2017/201705_2gram.txt
  python3 tools/build_thai_dict.py /tmp/pt/tnc_freq.txt /tmp/pt/words_th.txt /tmp/pt/2gram.txt

Hand-curated conversational words already in th_words.tsv (ครับ, ค่ะ, จ้า, ...)
are kept and never ranked lower than their curated frequency.
"""
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/dict/th_words.tsv"
CURATED = ROOT / "tools/th_curated.tsv"

MIN_COUNT = 5            # drop words seen fewer times than this
TRUSTED_COUNT = 50       # above this, keep even if not in the word list
MAX_WORDS = 40000        # memory budget on the phone
SCALE_MAX = 200000       # frequency given to the most common word
MAX_FOLLOWERS = 10       # next-word predictions kept per word
MIN_BIGRAM_COUNT = 15
BIGRAM_SCALE_MAX = 5000

THAI_WORD = re.compile(r"^[ก-๎]{1,30}$")
CANNOT_START = set("ะัาำิีึืฺุู็่้๊๋์ํ๎ๆฯ")
MARKS = set("ัิีึืฺุู็่้๊๋์ํ๎")


def plausible(word: str) -> bool:
    if not THAI_WORD.match(word) or word[0] in CANNOT_START:
        return False
    # two combining marks of the same kind in a row ("ครึ่่ง") are typos
    return not any(a in MARKS and a == b for a, b in zip(word, word[1:]))


def build_bigrams(path: str, vocab: set) -> None:
    followers = defaultdict(list)
    for line in open(path, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 3:
            continue
        a, b, count = parts[0], parts[1], int(parts[2])
        if count >= MIN_BIGRAM_COUNT and a in vocab and b in vocab:
            followers[a].append((b, count))
    top = max(c for lst in followers.values() for _, c in lst)
    bigrams = {}
    for prev, lst in followers.items():
        for w, c in sorted(lst, key=lambda x: -x[1])[:MAX_FOLLOWERS]:
            bigrams[(prev, w)] = max(1, round(BIGRAM_SCALE_MAX * math.sqrt(c / top)))
    for line in open(ROOT / "tools/th_curated_bigrams.tsv", encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        a, b, f = line.rstrip("\n").split("\t")
        bigrams[(a, b)] = max(bigrams.get((a, b), 0), int(f))
    out_path = ROOT / "app/src/main/assets/dict/th_bigrams.tsv"
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("# previous<TAB>word<TAB>frequency (Thai). Generated by tools/build_thai_dict.py\n")
        out.write("# Source: Thai National Corpus bigrams via PyThaiNLP corpus (CC0-1.0)\n")
        for (a, b), f in sorted(bigrams.items(), key=lambda kv: (kv[0][0], -kv[1])):
            out.write(f"{a}\t{b}\t{f}\n")
    print(f"wrote {len(bigrams)} bigrams to {out_path.relative_to(ROOT)}")


def main(tnc_path: str, words_path: str, bigrams_path: str = None) -> None:
    lexicon = {l.strip() for l in open(words_path, encoding="utf-8")}
    counts = {}
    for line in open(tnc_path, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 2:
            continue
        word, count = parts[0].strip(), int(parts[1])
        if count < MIN_COUNT or not plausible(word):
            continue
        if count < TRUSTED_COUNT and word not in lexicon:
            continue
        counts[word] = max(counts.get(word, 0), count)

    top = max(counts.values())
    freqs = {w: max(1, round(c * SCALE_MAX / top)) for w, c in counts.items()}
    ranked = sorted(freqs.items(), key=lambda kv: -kv[1])[:MAX_WORDS]
    freqs = dict(ranked)

    for line in open(CURATED, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        word, f = line.split("\t")
        freqs[word] = max(freqs.get(word, 0), int(f))

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("# word<TAB>frequency (Thai). Generated by tools/build_thai_dict.py\n")
        out.write("# Source: Thai National Corpus frequencies via PyThaiNLP corpus (CC0-1.0)\n")
        for word, f in sorted(freqs.items(), key=lambda kv: (-kv[1], kv[0])):
            out.write(f"{word}\t{f}\n")
    print(f"wrote {len(freqs)} words to {OUT.relative_to(ROOT)}")
    if bigrams_path:
        build_bigrams(bigrams_path, set(freqs))


if __name__ == "__main__":
    main(*sys.argv[1:4])
