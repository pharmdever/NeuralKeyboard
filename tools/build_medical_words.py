#!/usr/bin/env python3
"""Builds app/src/main/assets/dict/en_medwords.tsv (disease / anatomy / clinical words).

Source: ICD-10-CM tabular list, published by the US CDC / NCHS (public domain),
as packaged in the `simple-icd-10-cm` PyPI package. Every word used in the code
descriptions that the general dictionary lacks is added, weighted by how often
it occurs.

Usage:
  pip download --no-deps simple-icd-10-cm -d /tmp/icd
  unzip -j /tmp/icd/*.whl 'simple_icd_10_cm/data/icd10c-tabular-*.xml' -d /tmp/icd
  python3 tools/build_medical_words.py /tmp/icd/icd10c-tabular-*.xml
"""
import collections
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT = ROOT / "app/src/main/assets/dict"
EXTRA = ROOT / "tools/en_medwords_extra.txt"
MIN_COUNT = 2


def main(xml_path: str) -> None:
    xml = open(xml_path, encoding="utf-8", errors="replace").read()
    counts = collections.Counter()
    for text in re.findall(r"<(?:desc|note)>([^<]+)</(?:desc|note)>", xml):
        for w in re.findall(r"[A-Za-z]{4,}", text):
            counts[w.lower()] += 1
    general = {l.split("\t")[0] for l in open(DICT / "en_words.tsv", encoding="utf-8") if not l.startswith("#")}
    words = {w: min(2500, round(150 + 60 * math.sqrt(c))) for w, c in counts.items()
             if c >= MIN_COUNT and w not in general}
    for line in open(EXTRA, encoding="utf-8"):
        w = line.strip().lower()
        if w and not w.startswith("#"):
            words[w] = max(words.get(w, 0), 1200)
    with open(DICT / "en_medwords.tsv", "w", encoding="utf-8") as out:
        out.write("# Medical vocabulary<TAB>frequency. Generated by tools/build_medical_words.py\n")
        out.write("# Source: ICD-10-CM (US CDC/NCHS, public domain) + tools/en_medwords_extra.txt\n")
        for w, f in sorted(words.items()):
            out.write(f"{w}\t{f}\n")
    print(f"wrote {len(words)} medical words")


if __name__ == "__main__":
    main(sys.argv[1])
